package dev.tobi.manna.data.bible

import android.content.Context
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.sync.Mutex
import kotlinx.coroutines.sync.withLock
import kotlinx.coroutines.withContext
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json

@Serializable
data class BookInfo(val nr: Int, val name: String, val abbr: String, val chapters: Int)

@Serializable
data class TranslationInfo(val id: String, val name: String, val license: String = "", val books: List<BookInfo>)

@Serializable
private data class BookText(val chapters: List<List<String>>)

data class Verse(val book: Int, val chapter: Int, val verse: Int, val text: String)

/** Source of Bible text. Swappable so a licensed modern translation can be plugged in later. */
interface TextProvider {
    val translationId: String
    suspend fun info(): TranslationInfo
    suspend fun verses(book: Int, chapter: Int, from: Int, to: Int): List<Verse>
    suspend fun chapter(book: Int, chapter: Int): List<Verse>
}

/** Offline text bundled in assets/bible/<id>/ (generated by tools/build_bible_assets.py). */
class AssetTextProvider(
    private val context: Context,
    override val translationId: String = "elbbk",
) : TextProvider {
    private val json = Json { ignoreUnknownKeys = true }
    private val cache = HashMap<Int, BookText>()
    private val mutex = Mutex()
    private var infoCache: TranslationInfo? = null

    override suspend fun info(): TranslationInfo = mutex.withLock {
        infoCache ?: withContext(Dispatchers.IO) {
            json.decodeFromString<TranslationInfo>(read("bible/$translationId/books.json"))
        }.also { infoCache = it }
    }

    private suspend fun book(nr: Int): BookText = mutex.withLock {
        cache[nr] ?: withContext(Dispatchers.IO) {
            json.decodeFromString<BookText>(read("bible/$translationId/%02d.json".format(nr)))
        }.also { cache[nr] = it }
    }

    override suspend fun verses(book: Int, chapter: Int, from: Int, to: Int): List<Verse> {
        val ch = book(book).chapters[chapter - 1]
        // blank = verse omitted in this translation (e.g. Apg 8,37)
        return (from..to.coerceAtMost(ch.size)).map { Verse(book, chapter, it, ch[it - 1]) }.filter { it.text.isNotBlank() }
    }

    override suspend fun chapter(book: Int, chapter: Int): List<Verse> {
        val ch = book(book).chapters[chapter - 1]
        return ch.mapIndexed { i, t -> Verse(book, chapter, i + 1, t) }.filter { it.text.isNotBlank() }
    }

    private fun read(path: String) = context.assets.open(path).bufferedReader(Charsets.UTF_8).use { it.readText() }
}
